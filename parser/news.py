#!/usr/bin/env python3
"""msu.kz: новости/объявления -> out/news.sql (для D1). Запускается в Actions каждые ~15 минут.

Состояние (какие id уже видели) — data/news_seen.json. Первый запуск = «базовая линия»:
всё, что уже есть на сайте, помечается как старое (seen=0), чтобы бот не завалил подписчиков архивом.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

BASE = "https://www.msu.kz"
UA = {"User-Agent": "Mozilla/5.0 (compatible; msu-schedule-bot/1.0)"}
# порядок важен: первая лента, где встретилась новость, считается основной (для подписи в сообщении)
FEEDS = {
    "ann": "/ru/obyavleniya/",
    "news": "/ru/news/",
    "conf": "/ru/science/list.php?SECTION_ID=390",
    "lect": "/ru/science/list.php?SECTION_ID=376",
    "olymp": "/ru/science/olimpiady/",
    "school": "/ru/news/news.php?SECTION_ID=546",
}


def parse_items(html: str) -> list[dict]:
    from bs4 import BeautifulSoup
    soup = BeautifulSoup(html, "lxml")
    out, seen = [], set()
    for a in soup.find_all("a", string=re.compile("Подробнее")):
        m = re.search(r"ELEMENT_ID=(\d+)", a.get("href", ""))
        row = a.find_parent("div", class_="row")
        t = row.select_one(".fw-medium") if row else None
        if not m or not t or int(m.group(1)) in seen:
            continue
        seen.add(int(m.group(1)))
        href = a["href"]
        url = href if href.startswith("http") else BASE + href
        if not re.match(r"https://(www\.)?msu\.kz/", url):   # ссылки только на сайт филиала
            continue
        out.append({"id": int(m.group(1)), "title": re.sub(r"\s+", " ", t.get_text(" ", strip=True))[:300], "url": url})
    return out


def q(v) -> str:
    return "'" + str(v).replace("'", "''") + "'"


def build_sql(items: dict[int, dict], new_ids: set[int], baseline: bool) -> str:
    lines = ["-- generated by parser/news.py"]
    for i in sorted(new_ids):
        it = items[i]
        seen = "0" if baseline else "CAST(strftime('%s','now') AS INTEGER)"
        lines.append(
            f"INSERT INTO news (id, feed, feeds, title, url, seen) VALUES ({i}, {q(it['feeds'][0])}, {q(',' + ','.join(it['feeds']) + ',')}, "
            f"{q(it['title'])}, {q(it['url'])}, {seen}) ON CONFLICT(id) DO UPDATE SET feeds=excluded.feeds;")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--state", default="data/news_seen.json")
    ap.add_argument("--sql", default="out/news.sql")
    args = ap.parse_args()
    import httpx
    items: dict[int, dict] = {}
    ok = 0
    with httpx.Client(headers=UA, follow_redirects=True, timeout=40) as c:
        for feed, path in FEEDS.items():
            try:
                r = c.get(BASE + path)
                r.raise_for_status()
                got = parse_items(r.text)
            except Exception as e:  # noqa: BLE001
                print(f"::warning::{feed}: {e}")
                continue
            if not got:
                print(f"::warning::{feed}: на странице не найдено ни одной записи (вёрстка изменилась?)")
                continue
            ok += 1
            for it in got:
                d = items.setdefault(it["id"], {**it, "feeds": []})
                if feed not in d["feeds"]:
                    d["feeds"].append(feed)
            print(f"{feed:7} {len(got)} записей")
    if not ok:
        print("::error::ни одна лента не распознана")
        return 1
    st = Path(args.state)
    baseline = not st.exists()
    old = set(json.loads(st.read_text()) if st.exists() else [])
    # id уже известных новостей тоже пересылаем в SQL, если появилась новая лента — но это редкость; считаем «новыми» только неизвестные id
    new_ids = set(items) - old
    print(f"всего {len(items)}, новых {len(new_ids)}{' (базовая линия)' if baseline else ''}")
    Path(args.sql).parent.mkdir(parents=True, exist_ok=True)
    Path(args.sql).write_text(build_sql(items, new_ids, baseline), "utf-8")
    st.parent.mkdir(parents=True, exist_ok=True)
    st.write_text(json.dumps(sorted(old | set(items))), "utf-8")
    import os
    if os.getenv("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a") as f:
            f.write(f"new={'true' if new_ids else 'false'}\n")
    for i in sorted(new_ids)[-5:]:
        print("  +", i, items[i]["title"][:70])
    return 0


if __name__ == "__main__":
    sys.exit(main())
